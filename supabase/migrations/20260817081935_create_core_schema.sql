/*
# Kirinyaga Healthcare Workers Cafeteria POS — Core Schema

## Overview
Creates the complete relational schema for the cafeteria POS and management system.
All tables use RLS with authenticated-only access (this app has a sign-in screen).

## Tables Created

### Identity & Access
- `profiles` — staff accounts linked to auth.users, with role (super_admin/admin/cashier/storekeeper/accountant/auditor), employee_id, salary, status
- `stores` — multiple locations (main store, cafeteria, kitchen, branches)
- `audit_logs` — immutable record of sensitive operations (user, action, entity, old/new values)
- `settings` — key/value app configuration (M-Pesa config stored here, encrypted at app layer)
- `notifications` — in-app alerts (low stock, failed payments, etc.)

### Catalog & Inventory
- `categories` — product categories
- `products` — menu items with SKU, barcode, buying/selling price, image, allow_negative_stock flag
- `inventory` — per-product, per-store stock levels with minimum_stock
- `inventory_movements` — traceable stock changes (purchase/sale/adjustment/damage/expiry/transfer/return) with previous/new quantity, reason, user

### Customers & Dining
- `customers` — customer records with phone, employee_number, type (staff/visitor/student)
- `tables` — dining tables with status (available/occupied/payment_pending/paid/closed)
- `tabs` — open dine-in bills linked to table, customer, cashier, shift
- `tab_items` — products on a tab with quantity and price

### Sales & Payments
- `shifts` — cashier shifts with shift_number, opening/closing time, status, opening_cash (always 0 for M-Pesa only)
- `sales` — sales records with receipt_number, shift, cashier, customer, table, totals, status, payment_status
- `sale_items` — line items per sale
- `payments` — payment records (mpesa_stk/mpesa_paybill) with status, phone, mpesa_receipt_number, checkout/merchant request IDs
- `mpesa_transactions` — Daraja API transaction log with result_code, reconciliation_status

### Procurement & Finance
- `suppliers` — supplier records with outstanding balance
- `purchases` — purchase orders with supplier, invoice, payment status, balance
- `purchase_items` — line items per purchase
- `expenses` — expense records with category, amount, attachment
- `payroll` — salary records per employee per pay period

## Security
- RLS enabled on ALL tables
- All policies scoped TO authenticated
- profiles: users can read/update own profile; all authenticated can read profiles (staff directory)
- All business tables: authenticated users can read; writes restricted by application-level permission checks
  (RLS allows authenticated writes — fine-grained permission enforcement is in the app layer + audit logs)
- audit_logs: authenticated can read; inserts allowed for authenticated (system writes via service role)

## Important Notes
1. This is a multi-user app with sign-in. All policies are `TO authenticated`.
2. profiles.id references auth.users.id with DEFAULT auth.uid() so inserts work.
3. shift_number is auto-incremented per cashier via a sequence.
4. receipt_number format: RCP-YYYYMMDD-NNN generated by app.
5. M-Pesa credentials stored in settings table as encrypted values — secrets never in frontend.
*/

-- ============ PROFILES ============
CREATE TABLE IF NOT EXISTS profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email text NOT NULL,
  full_name text NOT NULL,
  employee_id text UNIQUE NOT NULL,
  phone text,
  position text,
  role text NOT NULL DEFAULT 'cashier' CHECK (role IN ('super_admin','admin','cashier','storekeeper','accountant','auditor')),
  salary numeric(12,2) DEFAULT 0,
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  date_joined date DEFAULT CURRENT_DATE,
  created_at timestamptz DEFAULT now()
);
ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "profiles_select_authenticated" ON profiles;
CREATE POLICY "profiles_select_authenticated" ON profiles FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "profiles_insert_own" ON profiles;
CREATE POLICY "profiles_insert_own" ON profiles FOR INSERT TO authenticated WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "profiles_update_own" ON profiles;
CREATE POLICY "profiles_update_own" ON profiles FOR UPDATE TO authenticated USING (auth.uid() = id) WITH CHECK (auth.uid() = id);

